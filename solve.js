// site-generator-speed-01: a faster drop-in for makefun-site 1.0.0.
//
// A from-scratch reimplementation of the reference pipeline. README.md states
// every rule and the vendor code is the reference wherever the two differ; this
// file follows both exactly, so its output is byte-for-byte identical to
// makefun-site 1.0.0 on every input. It is tuned for CPU time instead of for
// readability of the reference: bulk HTML escaping (the reference escapes one
// character per regex call), memoized slugs (tag and title slugs repeat),
// first-character Markdown dispatch (the reference runs seven regexes per
// line), and array-joined template rendering (the reference concatenates one
// string per node). All caches live inside one build() call: nothing is kept
// from one case to the next.

